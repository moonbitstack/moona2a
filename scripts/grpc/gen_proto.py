#!/usr/bin/env python3
"""Write the specification's `a2a.proto` into src/grpc/proto.mbt.

The gRPC binding reads its messages from the normative definition itself, so the file is
taken byte for byte from the specification at a pinned commit of v1.0.1.

    python3 scripts/grpc/gen_proto.py && moon fmt
"""

import pathlib
import urllib.request

COMMIT = "3303592588e388e62e0f69f701af531d2f4e3991"
URL = f"https://raw.githubusercontent.com/a2aproject/A2A/{COMMIT}/specification/a2a.proto"
OUT = pathlib.Path(__file__).resolve().parents[2] / "src" / "grpc" / "proto.mbt"


def main() -> None:
    with urllib.request.urlopen(URL, timeout=60) as response:
        text = response.read().decode("utf-8").replace("\r\n", "\n")
    lines = "\n".join(f"  #|{line}" for line in text.splitlines())
    OUT.write_text(
        "// Code generated by scripts/grpc/gen_proto.py from a2aproject/A2A at "
        f"{COMMIT[:7]} (v1.0.1). DO NOT EDIT.\n\n"
        "///|\n/// The specification's `a2a.proto`, the normative definition of the gRPC binding.\n"
        f"pub let a2a_proto : String =\n{lines}\n",
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    main()
